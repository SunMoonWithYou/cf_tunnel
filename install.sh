#!/usr/bin/env bash
# Cloudflare Tunnel Manager
# Debian / Ubuntu and Debian-based distributions with APT + systemd.
# cloudflared is installed ONLY from Cloudflare's official signed APT repository.

set -Eeuo pipefail
IFS=$'\n\t'

APP_NAME="Cloudflare Tunnel Manager"
APP_VERSION="4.0"
CF_KEY_URL="https://pkg.cloudflare.com/cloudflare-main.gpg"
CF_REPO_URL="https://pkg.cloudflare.com/cloudflared"
CF_KEYRING="/usr/share/keyrings/cloudflare-main.gpg"
CF_SOURCE="/etc/apt/sources.list.d/cloudflared.list"
CONFIG_DIR="/etc/cloudflared"
CONFIG_FILE="$CONFIG_DIR/config.yml"
CREDENTIAL_DIR="$CONFIG_DIR"
SERVICE_NAME="cloudflared-custom.service"
SERVICE_FILE="/etc/systemd/system/$SERVICE_NAME"
STATE_FILE="$CONFIG_DIR/manager.conf"
BACKUP_DIR="/var/backups/cloudflared-manager"

# ---------- Terminal styling ----------
if [[ -t 1 ]]; then
  C_RESET=$'\033[0m'; C_BOLD=$'\033[1m'; C_DIM=$'\033[2m'
  C_RED=$'\033[31m'; C_GREEN=$'\033[32m'; C_YELLOW=$'\033[33m'
  C_BLUE=$'\033[34m'; C_CYAN=$'\033[36m'; C_WHITE=$'\033[97m'
  C_BG_BLUE=$'\033[44m'
else
  C_RESET=''; C_BOLD=''; C_DIM=''; C_RED=''; C_GREEN=''
  C_YELLOW=''; C_BLUE=''; C_CYAN=''; C_WHITE=''; C_BG_BLUE=''
fi

info(){ printf '%sℹ%s %s\n' "$C_CYAN" "$C_RESET" "$*"; }
ok(){ printf '%s✔%s %s\n' "$C_GREEN" "$C_RESET" "$*"; }
warn(){ printf '%s!%s %s\n' "$C_YELLOW" "$C_RESET" "$*"; }
err(){ printf '%s✖%s %s\n' "$C_RED" "$C_RESET" "$*" >&2; }
pause(){ printf '\n'; read -r -p "按回车返回菜单..." _; }
confirm(){
  local answer
  read -r -p "$1 [y/N]: " answer
  [[ "$answer" =~ ^[Yy]$ ]]
}

# ---------- Basic checks ----------
require_root(){
  if [[ ${EUID:-$(id -u)} -ne 0 ]]; then
    err "请使用 root 运行：sudo bash $0"
    exit 1
  fi
}

detect_platform(){
  [[ -r /etc/os-release ]] || { err "找不到 /etc/os-release，无法识别系统"; exit 1; }
  # shellcheck disable=SC1091
  source /etc/os-release

  if ! command -v apt-get >/dev/null 2>&1; then
    err "当前系统没有 apt-get。此版本只使用 Cloudflare 官方 APT 仓库。"
    err "支持 Debian / Ubuntu 及其使用 APT 的衍生发行版；不支持 RHEL、Fedora、Arch、Alpine、macOS 或 Windows。"
    exit 1
  fi

  local family=" ${ID:-} ${ID_LIKE:-} "
  if [[ "$family" != *debian* && "$family" != *ubuntu* && "$ID" != "linuxmint" && "$ID" != "pop" && "$ID" != "kali" ]]; then
    warn "检测到系统：${PRETTY_NAME:-$ID}。它有 APT，但不一定属于 Cloudflare 官方明确测试的发行版。"
    if ! confirm "仍尝试使用 Cloudflare 官方 Debian APT 仓库吗？"; then exit 1; fi
  fi

  command -v systemctl >/dev/null 2>&1 || {
    err "当前系统没有 systemctl；此管理器需要 systemd。"
    exit 1
  }
  [[ "$(ps -p 1 -o comm= 2>/dev/null | tr -d ' ')" == "systemd" ]] || {
    err "当前系统 PID 1 不是 systemd，无法安装 systemd 服务。"
    exit 1
  }

  ARCH="$(dpkg --print-architecture 2>/dev/null || echo unknown)"
  info "系统：${PRETTY_NAME:-未知系统}"
  info "APT 架构：$ARCH"
}

# ---------- Official APT installation ----------
install_cloudflared(){
  export DEBIAN_FRONTEND=noninteractive

  info "安装基础依赖..."
  apt-get update
  apt-get install -y ca-certificates curl gnupg

  info "添加 Cloudflare 官方 APT 签名密钥..."
  install -d -m 0755 /usr/share/keyrings
  local key_tmp
  key_tmp="$(mktemp)"
  if ! curl -fL --retry 3 --connect-timeout 20 "$CF_KEY_URL" -o "$key_tmp"; then
    rm -f "$key_tmp"
    err "下载 Cloudflare 官方签名密钥失败。请检查服务器网络后重试。"
    return 1
  fi
  [[ -s "$key_tmp" ]] || { rm -f "$key_tmp"; err "签名密钥文件为空"; return 1; }
  install -m 0644 "$key_tmp" "$CF_KEYRING"
  rm -f "$key_tmp"

  info "配置 Cloudflare 官方稳定版 APT 仓库..."
  printf 'deb [signed-by=%s] %s any main\n' "$CF_KEYRING" "$CF_REPO_URL" > "$CF_SOURCE"

  info "更新软件包索引并安装 cloudflared..."
  apt-get update
  apt-get install -y cloudflared

  command -v cloudflared >/dev/null 2>&1 || {
    err "APT 安装完成，但找不到 cloudflared 命令"
    return 1
  }
  cloudflared --version
  ok "cloudflared 已通过 Cloudflare 官方 APT 仓库安装（APT 会校验仓库签名）。"
}

ensure_cloudflared(){
  if command -v cloudflared >/dev/null 2>&1; then
    info "已检测到 cloudflared：$(cloudflared --version 2>&1 | head -n 1)"
    if ! dpkg-query -W -f='${Status}' cloudflared 2>/dev/null | grep -q 'install ok installed'; then
      warn "当前 cloudflared 不是由 APT 的 cloudflared 软件包管理。"
      warn "为保持安装来源统一，建议先备份现有配置，再由官方 APT 软件包接管。"
    fi
    if dpkg-query -W -f='${Status}' cloudflared 2>/dev/null | grep -q 'install ok installed'; then
      if confirm "检查并升级 Cloudflare 官方 APT 仓库中的 cloudflared？"; then
        install_cloudflared
      fi
      return 0
    fi
    if ! confirm "是否安装 Cloudflare 官方 APT 版本？"; then return 1; fi
  fi
  install_cloudflared
}

# ---------- State helpers ----------
load_state(){
  [[ -f "$STATE_FILE" ]] || { err "尚无管理器配置。请先创建 Tunnel。"; return 1; }
  # State file is generated by this script and is root-readable only.
  # shellcheck disable=SC1090
  source "$STATE_FILE"
}

save_state(){
  install -d -m 0700 "$CONFIG_DIR"
  umask 077
  cat > "$STATE_FILE" <<EOF
TUNNEL_NAME=$(printf '%q' "$TUNNEL_NAME")
TUNNEL_ID=$(printf '%q' "$TUNNEL_ID")
PUBLIC_HOSTNAME=$(printf '%q' "$PUBLIC_HOSTNAME")
ORIGIN_URL=$(printf '%q' "$ORIGIN_URL")
EOF
  chmod 0600 "$STATE_FILE"
}

valid_hostname(){
  [[ "$1" =~ ^([A-Za-z0-9]([A-Za-z0-9-]{0,61}[A-Za-z0-9])?\.)+[A-Za-z]{2,63}$ ]]
}
valid_tunnel_name(){
  [[ "$1" =~ ^[A-Za-z0-9][A-Za-z0-9_-]{0,49}$ ]]
}
valid_origin(){
  [[ "$1" =~ ^https?://[A-Za-z0-9._:-]+(/[A-Za-z0-9._~:/?#\[\]@!$&\'()*+,;=%-]*)?$ ]]
}

write_config(){
  local id="$1" hostname="$2" origin="$3"
  install -d -m 0700 "$CONFIG_DIR"
  cat > "$CONFIG_FILE" <<EOF
tunnel: $id
credentials-file: $CONFIG_DIR/$id.json

ingress:
  - hostname: $hostname
    service: $origin
  - service: http_status:404
EOF
  chmod 0600 "$CONFIG_FILE"
}

# ---------- Create tunnel ----------
create_tunnel(){
  ensure_cloudflared || return 1
  install -d -m 0700 /root/.cloudflared "$CONFIG_DIR"

  printf '\n%s%s  浏览器授权  %s\n' "$C_BOLD" "$C_CYAN" "$C_RESET"
  echo "接下来会运行 cloudflared tunnel login。"
  echo "请复制终端输出的 Cloudflare 授权网址，在你自己的电脑浏览器打开。"
  echo "登录后选择已添加到 Cloudflare 的域名；授权成功后回到此终端。"
  pause

  if ! cloudflared tunnel login; then
    err "Cloudflare 浏览器授权失败或未完成。"
    return 1
  fi
  [[ -s /root/.cloudflared/cert.pem ]] || {
    err "没有找到 /root/.cloudflared/cert.pem；请确认授权是在当前服务器的 root 会话中完成。"
    return 1
  }
  chmod 0600 /root/.cloudflared/cert.pem

  local name hostname origin create_output
  read -r -p "Tunnel 名称（例如 my-home）: " name
  valid_tunnel_name "$name" || { err "名称格式不正确，只能使用字母、数字、_、-，且不能以符号开头"; return 1; }

  read -r -p "绑定的完整域名（例如 app.example.com）: " hostname
  valid_hostname "$hostname" || { err "域名格式不正确"; return 1; }

  read -r -p "本地服务地址（例如 http://localhost:8080）: " origin
  valid_origin "$origin" || { err "服务地址格式不正确，请输入 http:// 或 https:// 开头的地址"; return 1; }

  if [[ -e "$CONFIG_FILE" || -e "$SERVICE_FILE" ]]; then
    warn "检测到已有 Tunnel 配置或服务文件。"
    if ! confirm "继续创建并覆盖当前管理器配置？"; then return 1; fi
    mkdir -p "$BACKUP_DIR"
    [[ -f "$CONFIG_FILE" ]] && cp -a "$CONFIG_FILE" "$BACKUP_DIR/config.$(date +%Y%m%d-%H%M%S).yml"
    [[ -f "$SERVICE_FILE" ]] && cp -a "$SERVICE_FILE" "$BACKUP_DIR/service.$(date +%Y%m%d-%H%M%S)"
  fi

  info "正在创建 Tunnel：$name"
  if ! create_output="$(cloudflared tunnel create "$name" 2>&1)"; then
    printf '%s\n' "$create_output"
    err "Tunnel 创建失败。请检查名称是否已存在，以及账号授权是否正确。"
    return 1
  fi
  printf '%s\n' "$create_output"

  TUNNEL_ID="$(printf '%s\n' "$create_output" | grep -Eo '[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}' | tail -n 1 || true)"
  [[ -n "$TUNNEL_ID" ]] || {
    err "无法从 cloudflared 输出中解析 Tunnel UUID。Tunnel 可能已创建，请检查 cloudflared tunnel list。"
    return 1
  }

  [[ -s "/root/.cloudflared/$TUNNEL_ID.json" ]] || {
    err "未找到 Tunnel 凭据文件：/root/.cloudflared/$TUNNEL_ID.json"
    return 1
  }
  install -m 0600 "/root/.cloudflared/$TUNNEL_ID.json" "$CONFIG_DIR/$TUNNEL_ID.json"

  info "正在为 $hostname 创建 DNS 路由..."
  if ! cloudflared tunnel route dns "$TUNNEL_ID" "$hostname"; then
    err "DNS 路由配置失败。Tunnel 已创建，但 DNS 未确认成功。"
    warn "可检查域名是否在当前 Cloudflare 账号中，以及该 DNS 记录是否已存在。"
    return 1
  fi

  TUNNEL_NAME="$name"
  PUBLIC_HOSTNAME="$hostname"
  ORIGIN_URL="$origin"
  write_config "$TUNNEL_ID" "$PUBLIC_HOSTNAME" "$ORIGIN_URL"

  cat > "$SERVICE_FILE" <<EOF
[Unit]
Description=Cloudflare Tunnel ($TUNNEL_NAME)
Wants=network-online.target
After=network-online.target

[Service]
Type=simple
User=root
ExecStart=/usr/bin/cloudflared --no-autoupdate --config $CONFIG_FILE tunnel run
Restart=on-failure
RestartSec=5s
TimeoutStartSec=0

[Install]
WantedBy=multi-user.target
EOF
  chmod 0644 "$SERVICE_FILE"

  save_state
  systemctl daemon-reload
  systemctl enable --now "$SERVICE_NAME"

  if systemctl is-active --quiet "$SERVICE_NAME"; then
    ok "Tunnel 创建并启动成功！"
    printf '\n  公网地址：%shttps://%s%s\n' "$C_GREEN" "$PUBLIC_HOSTNAME" "$C_RESET"
    printf '  回源地址：%s\n' "$ORIGIN_URL"
    printf '  Tunnel ID：%s\n' "$TUNNEL_ID"
  else
    err "配置已写入，但服务未能正常启动。请查看日志。"
    systemctl --no-pager --full status "$SERVICE_NAME" || true
    return 1
  fi
}

# ---------- Service management ----------
service_action(){
  local action="$1"
  systemctl "$action" "$SERVICE_NAME"
  if [[ "$action" == "start" || "$action" == "restart" ]]; then
    sleep 2
    systemctl --no-pager --full status "$SERVICE_NAME" || true
  else
    ok "已执行：$action"
  fi
}

show_status(){
  if systemctl list-unit-files "$SERVICE_NAME" --no-legend 2>/dev/null | grep -q "$SERVICE_NAME"; then
    systemctl --no-pager --full status "$SERVICE_NAME" || true
  else
    warn "Tunnel 服务尚未安装。"
  fi
  if [[ -f "$STATE_FILE" ]]; then
    load_state || true
    printf '\n域名：%s\n回源：%s\nTunnel：%s\n' \
      "${PUBLIC_HOSTNAME:-未知}" "${ORIGIN_URL:-未知}" "${TUNNEL_ID:-未知}"
  fi
  if command -v cloudflared >/dev/null 2>&1; then
    printf '\n版本：%s\n' "$(cloudflared --version 2>&1 | head -n 1)"
  fi
}

show_logs(){
  if ! systemctl list-unit-files "$SERVICE_NAME" --no-legend 2>/dev/null | grep -q "$SERVICE_NAME"; then
    warn "服务尚未安装。"
    return
  fi
  echo "按 Ctrl+C 返回菜单。"
  journalctl -u "$SERVICE_NAME" -n 80 -f
}

edit_origin(){
  load_state || return 1
  local new_origin
  read -r -p "新的本地服务地址（当前：$ORIGIN_URL）: " new_origin
  valid_origin "$new_origin" || { err "地址格式不正确"; return 1; }

  cp -a "$CONFIG_FILE" "$BACKUP_DIR/config.$(date +%Y%m%d-%H%M%S).yml" 2>/dev/null || true
  ORIGIN_URL="$new_origin"
  write_config "$TUNNEL_ID" "$PUBLIC_HOSTNAME" "$ORIGIN_URL"
  save_state
  systemctl restart "$SERVICE_NAME"
  ok "回源地址已更新。"
}

edit_hostname(){
  load_state || return 1
  local new_host
  read -r -p "新的完整域名（当前：$PUBLIC_HOSTNAME）: " new_host
  valid_hostname "$new_host" || { err "域名格式不正确"; return 1; }
  warn "这会尝试为新域名创建 DNS 路由；旧 DNS 记录不会自动删除。"
  cloudflared tunnel route dns "$TUNNEL_ID" "$new_host" || return 1
  PUBLIC_HOSTNAME="$new_host"
  write_config "$TUNNEL_ID" "$PUBLIC_HOSTNAME" "$ORIGIN_URL"
  save_state
  systemctl restart "$SERVICE_NAME"
  ok "域名配置已更新。请自行确认旧 DNS 记录是否需要删除。"
}

update_cloudflared(){
  info "通过 Cloudflare 官方 APT 仓库更新 cloudflared..."
  apt-get update
  apt-get install --only-upgrade -y cloudflared
  systemctl restart "$SERVICE_NAME" 2>/dev/null || true
  cloudflared --version
  ok "更新检查完成。"
}

uninstall_local(){
  warn "此操作会停止并移除本机 systemd 服务。"
  if ! confirm "确定卸载本机 Tunnel 管理配置？"; then return; fi
  systemctl disable --now "$SERVICE_NAME" 2>/dev/null || true
  rm -f "$SERVICE_FILE"
  systemctl daemon-reload
  if confirm "同时删除 /etc/cloudflared 下的配置和凭据？"; then
    rm -rf "$CONFIG_DIR"
  fi
  if confirm "同时通过 APT 卸载 cloudflared 软件包？"; then
    apt-get remove -y cloudflared
  fi
  warn "此操作不会删除 Cloudflare 云端 Tunnel 或 DNS 记录。"
  ok "本机卸载步骤完成。"
}

# ---------- Menu UI ----------
draw_header(){
  clear 2>/dev/null || true
  printf '%s' "$C_CYAN"
  cat <<'BANNER'
   ____  _                 __ _are
  / ___|| | ___  _   _  __/ _| | __ _ _ __ ___
 | |    | |/ _ \| | | |/ _` | |/ _` | '__/ _ \
 | |___ | | (_) | |_| | (_| | | (_| | | |  __/
  \____||_|\___/ \__,_|\__,_|_|\__,_|_|  \___|
BANNER
  printf '%s' "$C_RESET"
  printf '%s%s  %s  %s%s\n' "$C_BOLD" "$C_WHITE" "$APP_NAME" "v$APP_VERSION" "$C_RESET"
  printf '%s\n' "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
  printf ' 系统：%s | 架构：%s\n' "${PRETTY_NAME:-Linux}" "${ARCH:-unknown}"
  if systemctl is-active --quiet "$SERVICE_NAME" 2>/dev/null; then
    printf ' 状态：%s● 运行中%s\n' "$C_GREEN" "$C_RESET"
  elif systemctl is-enabled --quiet "$SERVICE_NAME" 2>/dev/null; then
    printf ' 状态：%s● 已安装 / 未运行%s\n' "$C_YELLOW" "$C_RESET"
  else
    printf ' 状态：%s● 尚未配置%s\n' "$C_DIM" "$C_RESET"
  fi
  printf '%s\n' "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
}

menu_item(){
  printf '  %s%s%s  %s\n' "$C_CYAN" "$1" "$C_RESET" "$2"
}

main_menu(){
  while true; do
    draw_header
    printf '\n%s【Tunnel 配置】%s\n' "$C_BOLD" "$C_RESET"
    menu_item "1" "安装 cloudflared 并创建 Tunnel"
    menu_item "2" "修改本地服务地址 / 端口"
    menu_item "3" "修改绑定域名"
    printf '\n%s【服务管理】%s\n' "$C_BOLD" "$C_RESET"
    menu_item "4" "启动服务"
    menu_item "5" "停止服务"
    menu_item "6" "重启服务"
    menu_item "7" "查看运行状态"
    menu_item "8" "查看实时日志"
    printf '\n%s【维护】%s\n' "$C_BOLD" "$C_RESET"
    menu_item "9" "通过官方 APT 仓库更新 cloudflared"
    menu_item "10" "卸载本机服务 / 配置"
    menu_item "0" "退出"
    printf '\n%s\n' "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
    local choice
    read -r -p "  请输入选项 [0-10]: " choice
    case "$choice" in
      1) create_tunnel; pause ;;
      2) edit_origin; pause ;;
      3) edit_hostname; pause ;;
      4) service_action start; pause ;;
      5) service_action stop; pause ;;
      6) service_action restart; pause ;;
      7) show_status; pause ;;
      8) show_logs; pause ;;
      9) update_cloudflared; pause ;;
      10) uninstall_local; pause ;;
      0) printf '\n再见！\n'; exit 0 ;;
      *) warn "无效选项"; sleep 1 ;;
    esac
  done
}

require_root
detect_platform
main_menu
